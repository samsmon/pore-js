async function demoPdf() {
  const dir = 'demo-pdf';
  const pdf = await PDFDocument.create();
  pdf.setTitle('The Pore.js Demo PDF');
  const font = await pdf.embedFont(StandardFonts.TimesRoman);
  const bold = await pdf.embedFont(StandardFonts.TimesRomanBold);
  const sections = ['Introduction', 'The Middle Part', 'Closing Notes'];
  sections.forEach((title, i) => {
    for (let k = 0; k < 3; k++) {
      const page = pdf.addPage([595, 842]); // A4
      page.drawText(k === 0 ? title : `${title} (cont.)`, {
        x: 64,
        y: 780,
        size: k === 0 ? 22 : 14,
        font: bold,
        color: rgb(0.1, 0.1, 0.1),
      });
      const body = (LOREM.repeat(3) + ' ' + LOREM.repeat(2)).match(/.{1,84}(\s|$)/g) ?? [];
      body.slice(0, 30).forEach((line, li) => {
        page.drawText(line.trim(), { x: 64, y: 740 - li * 22, size: 11, font });
      });
      page.drawText(`${i * 3 + k + 1}`, { x: 297, y: 32, size: 10, font });
    }
  });

  const bytes = await pdf.save();
  await emit(dir, 'book.pdf', bytes);
  await emit(
    dir,
    'manifest.json',
    JSON.stringify({ type: 'pdf', title: 'The Pore.js Demo PDF', file: 'book.pdf' }, null, 2),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic PDF generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-pdf\n\nProcedurally generated placeholder PDF. Not a real work.\n',
  );
}

