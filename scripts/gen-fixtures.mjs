#!/usr/bin/env node
/**
 * Generates the demo fixtures (SVG "pages" + manifest.json) into
 * apps/demo/public/fixtures/. Synthetic art — no licensing concerns.
 *
 *   node scripts/gen-fixtures.mjs
 */
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zipSync } from 'fflate';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import {
  AR,
  JP,
  LOREM,
  buildDemoBookFiles,
  buildFixedBookFiles,
  buildLocalizedEpubFiles,
  pageSvg,
} from './fixture-templates.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = join(root, 'apps/demo/public/fixtures');

async function emit(dir, name, contents) {
  const path = join(outRoot, dir, name);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}

async function manga() {
  const dir = 'demo-manga';
  const W = 840;
  const H = 1200;
  const pages = [];
  let n = 0;
  for (let p = 1; p <= 12; p++) {
    // page 6 is a wide double-page spread
    const wide = p === 6;
    const w = wide ? W * 2 : W;
    const file = `p${String(p).padStart(2, '0')}.svg`;
    await emit(
      dir,
      file,
      pageSvg({
        w,
        h: H,
        label: wide ? `SPREAD ${p}` : `PAGE ${p}`,
        sub: 'demo-manga · RTL · CC0',
        n: n++,
      }),
    );
    pages.push({ src: file, width: w, height: H, ...(wide ? { isWide: true } : {}) });
  }
  await emit(
    dir,
    'manifest.json',
    JSON.stringify(
      {
        type: 'image',
        title: 'Demo Manga (synthetic)',
        direction: 'rtl',
        preferredLayout: 'paged-double',
        chapters: [
          { id: 'ch1', label: 'Chapter 1 — Arrival', startIndex: 0 },
          { id: 'ch2', label: 'Chapter 2 — The Spread', startIndex: 5 },
          { id: 'ch3', label: 'Chapter 3 — Aftermath', startIndex: 9 },
        ],
        pages,
      },
      null,
      2,
    ),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic art generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-manga\n\nProcedurally generated placeholder pages. Not a real work.\n',
  );
}

